"""Exact branded beta rendition, no remote assets or member identifiers."""
import logging
from dataclasses import dataclass,field
from hashlib import sha256

from penny.guardian.policy import authorize
from penny.guardian.state import Actor,Capability
from penny.memory.review import _valid_id
from penny.scheduler.storage_db import locked
from .edition import build_locked
from .preview import read_preview_locked

logger=logging.getLogger(__name__)


@dataclass(frozen=True,slots=True)
class BetaProof:
    edition_sha256: str
    variant_sha256: str
    content: bytes=field(repr=False)


def proof_locked(conn,preview_id,grant_id,now,*,quality_review_id,brand_version,artwork):
    if read_preview_locked(conn,preview_id,now) is None:
        return None
    p=conn.execute("SELECT task_id,artifact_sha256 FROM workshop_preview WHERE id=%s",
                   (preview_id,)).fetchone()
    edition=build_locked(conn,p["task_id"],now,review_id=quality_review_id,
                         source_sha256=p["artifact_sha256"],brand_version=brand_version,artwork=artwork)
    if edition is None:
        return None
    # An opaque grant UUID only, not a name, email or member ID. Exact
    # generated bytes must be reviewed before the grant is approved.
    marker=b"<footer>"
    if edition.content.count(marker)!=1:
        return None
    watermark=("<footer><p>CLOSED BETA — Review copy "+str(grant_id)+
               " — not for redistribution.</p>").encode("utf-8")
    content=edition.content.replace(marker,watermark,1)
    return BetaProof(edition.edition_sha256,sha256(content).hexdigest(),content)


def prepare_beta(dsn,preview_id,grant_id,*,quality_review_id,brand_version,artwork):
    try:
        if not all(_valid_id(x) for x in (preview_id,grant_id,quality_review_id)):
            raise ValueError("invalid beta proof identity")
        if not authorize(Actor.ADMIN,Capability.REVIEW_PRODUCT_CATALOG).allowed:
            return None
        with locked(dsn) as (conn,_,now):
            return proof_locked(conn,preview_id,grant_id,now,quality_review_id=quality_review_id,
                                brand_version=brand_version,artwork=artwork)
    except Exception as exc:
        logger.error("Beta preparation refused (%s)",type(exc).__name__)
        raise
